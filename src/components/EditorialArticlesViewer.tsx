import { useState } from 'react';
import { useTranslation } from 'react-i18next';
import { editorialArticles, EditorialArticle } from '../data/editorialArticles';
import { BookOpen, ArrowLeft, Clock, Printer, Download, AlertTriangle, FileText, CheckCircle } from 'lucide-react';

export default function EditorialArticlesViewer({ theme }: { theme: 'dark' | 'light' }) {
  const { t, i18n } = useTranslation();
  const currentLang = i18n.language || 'en';

  const [activeArticleId, setActiveArticleId] = useState<string | null>(null);

  const selectedArticle = editorialArticles.find(a => a.id === activeArticleId);

  const handleDownloadNote = (article: EditorialArticle) => {
    const isNo = currentLang === 'no';
    const title = isNo ? article.titleNo : article.title;
    const summary = isNo ? article.summaryNo : article.summary;
    const takeaways = isNo ? article.keyTakeawaysNo : article.keyTakeaways;
    const printTitle = isNo ? article.printSummary.titleNo : article.printSummary.title;
    const printBullets = isNo ? article.printSummary.bulletsNo : article.printSummary.bullets;
    const sources = article.sources;

    const content = `==================================================
${title.toUpperCase()}
==================================================
Estimated Read Time: ${article.estimatedReadMinutes} minutes
Category: ${article.category}

OVERVIEW:
${summary}

KEY TAKEAWAYS:
${takeaways.map((tText, i) => `${i + 1}. ${tText}`).join('\n')}

--------------------------------------------------
${printTitle.toUpperCase()}
(Action items for reference / printing)
--------------------------------------------------
${printBullets.map(b => `- [ ] ${b}`).join('\n')}

SOURCES & REFERENCE DOCUMENTATION:
${sources.map(s => `- ${s}`).join('\n')}

==================================================
Generated by Beredskap101 | Offline Resilience Hub
==================================================
`;

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${article.id}_summary_card.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  // Custom styling mappings
  const styles = {
    cardBg: 'bg-[var(--card)] border border-[var(--border)]',
    titleText: 'text-[var(--text)] font-display',
    bodyText: 'text-[var(--text)] font-sans',
    btnActive: 'bg-[var(--accent)]/10 text-[var(--accent)] border-[var(--accent)]',
    btnInactive: 'bg-[var(--card)] text-[var(--muted)] border-[var(--border)] hover:border-[var(--muted)]/50 hover:text-[var(--text)]',
    accentText: 'text-[var(--accent)]',
    accentBorder: 'border-[var(--accent)]',
    badge: 'bg-[var(--accent)]/10 border border-[var(--accent)]/20 text-[var(--accent)]',
    bodyBg: 'bg-[var(--bg-alt)] border border-[var(--border)]',
    codeBg: 'bg-[var(--bg-alt)] border border-[var(--border)]'
  };

  if (selectedArticle) {
    const isNo = currentLang === 'no';
    const title = isNo ? selectedArticle.titleNo : selectedArticle.title;
    const summary = isNo ? selectedArticle.summaryNo : selectedArticle.summary;
    const takeaways = isNo ? selectedArticle.keyTakeawaysNo : selectedArticle.keyTakeaways;
    const printTitle = isNo ? selectedArticle.printSummary.titleNo : selectedArticle.printSummary.title;
    const printBullets = isNo ? selectedArticle.printSummary.bulletsNo : selectedArticle.printSummary.bullets;

    return (
      <div className="space-y-6 max-w-4xl mx-auto animate-fade-in print:p-0">
        {/* Back button and action headers */}
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-[var(--border)] pb-4 print:hidden">
          <button
            onClick={() => {
              setActiveArticleId(null);
              setTimeout(() => {
                document.getElementById('editorial-articles-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
              }, 50);
            }}
            className="px-4 py-2 bg-[var(--card)] border border-[var(--border)] rounded-xl text-xs font-bold flex items-center gap-1.5 hover:bg-[var(--bg-alt)] transition-all cursor-pointer"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            {isNo ? 'Tilbake til artikler' : 'Back to Articles'}
          </button>

          <div className="flex gap-2">
            <button
              onClick={() => handleDownloadNote(selectedArticle)}
              className="px-4 py-2 bg-[var(--card)] hover:bg-[var(--bg-alt)] border border-[var(--border)] hover:border-[var(--accent)] rounded-xl text-xs font-bold flex items-center gap-1.5 transition-all cursor-pointer"
              title={isNo ? 'Last ned sammendragskort' : 'Download Summary Card'}
            >
              <Download className="w-3.5 h-3.5" />
              {isNo ? 'Lagre notat (TXT)' : 'Save Note (TXT)'}
            </button>
            <button
              onClick={handlePrint}
              className="px-4 py-2 bg-[var(--card)] hover:bg-[var(--bg-alt)] border border-[var(--border)] hover:border-[var(--accent)] rounded-xl text-xs font-bold flex items-center gap-1.5 transition-all cursor-pointer"
              title={isNo ? 'Skriv ut sammendrag' : 'Print Summary'}
            >
              <Printer className="w-3.5 h-3.5" />
              {isNo ? 'Skriv ut' : 'Print'}
            </button>
          </div>
        </div>

        {/* Full Article Content */}
        <article className={`p-6 md:p-8 rounded-xl border shadow-sm ${styles.cardBg} space-y-6 print:border-none print:shadow-none print:p-0`}>
          <div className="border-b border-dashed border-[var(--border)] pb-4 flex flex-col gap-2">
            <div className="flex flex-wrap items-center gap-2">
              <span className={`text-[9px] font-mono uppercase font-bold px-2 py-0.5 rounded border ${styles.badge}`}>
                {selectedArticle.category}
              </span>
              <span className="text-[10px] text-[var(--muted)] font-mono flex items-center gap-1">
                <Clock className="w-3 h-3" />
                {selectedArticle.estimatedReadMinutes} {isNo ? 'min lesing' : 'min read'}
              </span>
            </div>
            <h2 className={`text-2xl md:text-3xl font-black ${styles.titleText} mt-1 leading-tight`}>
              {title}
            </h2>
            <p className="text-[10px] text-[var(--muted)] font-mono">Reference Code: {selectedArticle.id}</p>
          </div>

          {/* Executive Summary */}
          <div className={`p-5 rounded-xl border-l-4 ${styles.accentBorder} ${styles.bodyBg} leading-relaxed`}>
            <h4 className="text-xs font-mono font-bold uppercase text-[var(--accent)] mb-1.5 flex items-center gap-1.5">
              <FileText className="w-4 h-4" />
              {isNo ? 'Sammendrag' : 'Executive Summary'}
            </h4>
            <p className="text-xs md:text-sm text-[var(--text)]">{summary}</p>
          </div>

          {/* Key Takeaways */}
          <div className="space-y-3">
            <h4 className="text-xs font-mono font-bold uppercase text-[var(--muted)] tracking-wider">
              {isNo ? 'Viktige Læringspunkter' : 'Key Takeaways'}
            </h4>
            <div className="grid grid-cols-1 gap-2.5">
              {takeaways.map((takeaway, idx) => (
                <div key={idx} className={`p-3 rounded-lg border flex items-start gap-3 ${styles.bodyBg}`}>
                  <CheckCircle className={`w-4 h-4 mt-0.5 flex-shrink-0 ${styles.accentText}`} />
                  <p className={`text-xs md:text-sm ${theme === 'dark' ? 'text-neutral-200' : 'text-slate-800'}`}>{takeaway}</p>
                </div>
              ))}
            </div>
          </div>

          {/* Structured Body Sections */}
          <div className="space-y-6 pt-4 border-t border-dashed border-[var(--border)]">
            {selectedArticle.body.map((section, idx) => {
              const heading = isNo ? section.headingNo : section.heading;
              const content = isNo ? section.contentNo : section.content;
              return (
                <div key={idx} className="space-y-2">
                  <h3 className={`text-lg font-bold ${theme === 'dark' ? 'text-neutral-100' : 'text-slate-900'}`}>{heading}</h3>
                  <p className={`text-xs md:text-sm leading-relaxed font-sans ${theme === 'dark' ? 'text-neutral-300' : 'text-slate-700'}`}>
                    {content}
                  </p>
                </div>
              );
            })}
          </div>

          {/* Printable Summary Card Block (Constraint 3) */}
          <div className="pt-6 border-t border-[var(--border)]">
            <div className={`p-5 rounded-xl border border-dashed ${styles.accentBorder} ${styles.bodyBg} space-y-4 print:border-solid`}>
              <div className="flex items-center justify-between border-b border-dashed border-[var(--border)] pb-3">
                <h4 className="text-xs font-mono font-bold uppercase text-[var(--accent)] flex items-center gap-1.5">
                  <Printer className="w-4 h-4" />
                  {printTitle}
                </h4>
                <span className="text-[9px] font-mono text-[var(--muted)] border border-[var(--border)] px-2 py-0.5 rounded uppercase">
                  {isNo ? 'Utskriftskort' : 'Printable Card'}
                </span>
              </div>
              <ul className="space-y-2">
                {printBullets.map((bullet, idx) => (
                  <li key={idx} className={`flex items-start gap-2.5 text-xs ${theme === 'dark' ? 'text-neutral-200' : 'text-slate-800'}`}>
                    <span className="text-[var(--accent)] font-mono mt-0.5 flex-shrink-0">&#9634;</span>
                    <p>{bullet}</p>
                  </li>
                ))}
              </ul>
              <div className="text-[10px] text-[var(--muted)] font-mono flex flex-wrap justify-between pt-2 border-t border-dashed border-[var(--border)]/50">
                <span>Beredskap101 Corp</span>
                <span>Verification Code: B101-ED-${selectedArticle.id.substring(0, 5).toUpperCase()}</span>
              </div>
            </div>
          </div>

          {/* Sources and Attributions */}
          <div className="pt-4 border-t border-[var(--border)] space-y-2">
            <h5 className="text-[10px] font-mono uppercase tracking-wider text-[var(--muted)]">
              {isNo ? 'Kildegrunnlag & Dokumentasjon' : 'Primary Source Material & Attributions'}
            </h5>
            <ul className="space-y-1 text-xs text-[var(--muted)] font-mono">
              {selectedArticle.sources.map((source, idx) => (
                <li key={idx} className="flex items-start gap-2">
                  <span className="text-[var(--accent)]">&bull;</span>
                  <span>{source}</span>
                </li>
              ))}
            </ul>
          </div>
        </article>
      </div>
    );
  }

  // Gallery Overview
  const isNo = currentLang === 'no';
  return (
    <div className="space-y-6">
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {editorialArticles.map((article) => {
          const title = isNo ? article.titleNo : article.title;
          const summary = isNo ? article.summaryNo : article.summary;

          return (
            <article
              key={article.id}
              onClick={() => {
                setActiveArticleId(article.id);
                setTimeout(() => {
                  document.getElementById('editorial-articles-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }, 50);
              }}
              className={`p-6 rounded-xl border cursor-pointer hover:border-[var(--accent)]/50 hover:-translate-y-1 transition-all duration-300 flex flex-col justify-between min-h-[220px] ${styles.cardBg}`}
            >
              <div className="space-y-3">
                <div className="flex items-center justify-between">
                  <span className={`text-[9px] font-mono uppercase font-bold px-2 py-0.5 rounded border ${styles.badge}`}>
                    {article.category}
                  </span>
                  <span className="text-[10px] text-[var(--muted)] font-mono flex items-center gap-1">
                    <Clock className="w-3 h-3" />
                    {article.estimatedReadMinutes} {isNo ? 'min' : 'min read'}
                  </span>
                </div>

                <h3 className={`text-base md:text-lg font-bold leading-snug ${theme === 'dark' ? 'text-neutral-100' : 'text-slate-900'}`}>
                  {title}
                </h3>

                <p className="text-xs text-[var(--muted)] line-clamp-3 leading-relaxed">
                  {summary}
                </p>
              </div>

              <div className="mt-4 pt-3 border-t border-[var(--border)] flex items-center justify-between text-[11px] font-mono">
                <span className="opacity-70 text-[10px] text-[var(--muted)]">Source: {article.sources[0].split(' ? ')[0].split(' - ')[0]}</span>
                <span className="font-bold text-[var(--accent)] flex items-center gap-0.5">
                  {isNo ? 'Les artikkel' : 'Read Article'} &rarr;
                </span>
              </div>
            </article>
          );
        })}
      </div>
    </div>
  );
}
